import { useMemo, useState } from 'react'
import { Figure, Controls, Readout, Toggle, useNarrow } from '../../../../../kit'
import { Py, CodePanel, OutBox, CopyButton, Chips } from './code'
import { TRANSLATIONS } from './translations'
import s from './tep.module.css'

/*
  A searchable NumPy -> PyTorch phrasebook. Every example output was produced by running the
  snippet (see translations.ts, generated by a script). Rows marked TRAP behave differently in the
  two libraries.
*/

const GROUPS = ['All', 'Create', 'Shape', 'Reduce', 'Combine', 'Select', 'Maths', 'Convert'] as const
type Group = (typeof GROUPS)[number]

export default function TranslationTable() {
  const [query, setQuery] = useState('')
  const [group, setGroup] = useState<Group>('All')
  const [trapsOnly, setTrapsOnly] = useState(false)
  const [open, setOpen] = useState<number | null>(1)
  const [wrapRef, narrow] = useNarrow<HTMLDivElement>(560)

  const rows = useMemo(() => {
    const q = query.trim().toLowerCase()
    return TRANSLATIONS.filter((r) => {
      if (group !== 'All' && r.group !== group) return false
      if (trapsOnly && !r.trap) return false
      if (!q) return true
      return [r.np, r.torch, r.note, r.group, r.npCode, r.torchCode].some((t) => t.toLowerCase().includes(q))
    })
  }, [query, group, trapsOnly])

  const traps = TRANSLATIONS.filter((r) => r.trap).length

  return (
    <Figure
      wide
      title="NumPy to PyTorch phrasebook"
      caption={
        <>
          Search for an operation (try <code>concat</code>, <code>axis</code>, <code>max</code> or <code>dtype</code>) and click a row to see both versions run, with
          their real output. Most rows are a straight swap (<code>axis</code> becomes <code>dim</code>, <code>np.</code> becomes <code>torch.</code>); the{' '}
          {traps} rows marked <b>trap</b> behave differently and are worth memorising.
        </>
      }
    >
      <div ref={wrapRef} className={narrow ? s.narrow : ''} style={{ width: '100%', display: 'grid', gap: '0.7rem' }}>
        <input
          className={s.search}
          type="search"
          value={query}
          placeholder="Search: sum, cat, where, item, float64…"
          aria-label="Search NumPy or PyTorch operations"
          onChange={(e) => setQuery(e.target.value)}
        />
        <div className={s.filterRow}>
          <Chips label="Group" options={GROUPS.map((g) => ({ value: g, label: g }))} value={group} onChange={setGroup} />
        </div>
        <div className={s.ttList} role="list" aria-label="NumPy and PyTorch equivalents">
          <div className={s.ttHead} aria-hidden="true">
            <span>NumPy</span>
            <span>PyTorch</span>
          </div>
          {rows.length === 0 && <div className={s.ttEmpty}>No match. Try a shorter word, or clear the filters.</div>}
          {rows.map((r) => {
            const isOpen = open === r.id
            return (
              <div key={r.id} role="listitem" className={`${s.ttItem} ${isOpen ? s.ttOpen : ''}`}>
                <button type="button" className={s.ttRow} aria-expanded={isOpen} onClick={() => setOpen(isOpen ? null : r.id)}>
                  <span className={s.ttCell}>
                    <span className={s.ttTag}>NP</span>
                    <Py code={r.np} size={narrow ? 12 : 13} />
                  </span>
                  <span className={s.ttCell}>
                    <span className={s.ttTag}>PT</span>
                    <span>
                      <Py code={r.torch} size={narrow ? 12 : 13} />
                      {r.trap && <span className={s.trap}>trap</span>}
                    </span>
                  </span>
                </button>
                {isOpen && (
                  <div className={s.ttDetail}>
                    <div className={s.ttNote}>{r.note}</div>
                    <div className={s.ttPair}>
                      <div style={{ display: 'grid', gap: '0.4rem', minWidth: 0 }}>
                        <CodePanel title="NumPy" lines={r.npCode.split('\n')} size={12.5} right={<CopyButton text={`import numpy as np\n${r.npCode}`} />} />
                        <OutBox title="output">{r.npOut}</OutBox>
                      </div>
                      <div style={{ display: 'grid', gap: '0.4rem', minWidth: 0 }}>
                        <CodePanel title="PyTorch" lines={r.torchCode.split('\n')} size={12.5} right={<CopyButton text={`import numpy as np\nimport torch\n${r.torchCode}`} />} />
                        <OutBox title="output" tone="out">
                          {r.torchOut}
                        </OutBox>
                      </div>
                    </div>
                  </div>
                )}
              </div>
            )
          })}
        </div>
        <Controls>
          <Toggle label="Show traps only" checked={trapsOnly} onChange={setTrapsOnly} />
          <Readout items={[['rows shown', `${rows.length} of ${TRANSLATIONS.length}`]]} />
        </Controls>
      </div>
    </Figure>
  )
}
