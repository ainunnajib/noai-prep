export type Metric = 'euclidean' | 'manhattan'

/** Distance used for ranking: squared Euclidean (same order as Euclidean, no square root) or Manhattan. */
export function rankDist(m: Metric, ax: number, ay: number, bx: number, by: number) {
  const dx = ax - bx
  const dy = ay - by
  return m === 'euclidean' ? dx * dx + dy * dy : Math.abs(dx) + Math.abs(dy)
}

/** The real distance (what you would quote): Euclidean takes the square root. */
export function realDist(m: Metric, ax: number, ay: number, bx: number, by: number) {
  const r = rankDist(m, ax, ay, bx, by)
  return m === 'euclidean' ? Math.sqrt(r) : r
}

/** Indices of the k nearest training points, nearest first (ties broken by lower index, like a stable sort). */
export function nearest(data: readonly Pt[], qx: number, qy: number, k: number, m: Metric): number[] {
  const order = data.map((p, i) => [rankDist(m, qx, qy, p[0], p[1]), i] as const)
  order.sort((a, b) => a[0] - b[0] || a[1] - b[1])
  return order.slice(0, k).map((o) => o[1])
}

/**
 * Share of the k nearest neighbours that are class 1. Same result as nearest(), but keeps only a small
 * sorted buffer of the best k (fast enough to colour thousands of grid cells). Points are visited in index
 * order and an equal distance never overtakes, so ties go to the lower index exactly as in nearest().
 */
const bufD = new Float64Array(64)
const bufL = new Uint8Array(64)
export function voteShare(data: readonly Pt[], qx: number, qy: number, k: number, m: Metric): number {
  let filled = 0
  for (let i = 0; i < data.length; i++) {
    const p = data[i]
    const d = rankDist(m, qx, qy, p[0], p[1])
    if (filled === k && d >= bufD[k - 1]) continue
    let j = filled < k ? filled++ : k - 1
    while (j > 0 && bufD[j - 1] > d) {
      bufD[j] = bufD[j - 1]
      bufL[j] = bufL[j - 1]
      j--
    }
    bufD[j] = d
    bufL[j] = p[2]
  }
  let ones = 0
  for (let j = 0; j < k; j++) ones += bufL[j]
  return ones / k
}

/** Accuracy of k-NN (trained on TRAIN) on a labelled set; k odd so a two-class vote never ties. */
export function accuracy(evalSet: readonly Pt[], k: number, m: Metric): number {
  let right = 0
  for (const p of evalSet) {
    const pred = voteShare(TRAIN, p[0], p[1], k, m) > 0.5 ? 1 : 0
    if (pred === p[2]) right++
  }
  return right / evalSet.length
}

export interface Cell {
  x0: number
  x1: number
  y0: number
  y1: number
  /** predicted class */
  cls: 0 | 1
  /** confidence level 1..3 from the vote margin */
  level: number
}

/** Colour the square by the k-NN vote, merging neighbouring cells with the same class and level. */
export function voteRuns(k: number, m: Metric, n = 80, lo = 0, hi = 10): Cell[] {
  const step = (hi - lo) / n
  const runs: Cell[] = []
  const key = (x: number, y: number) => {
    const f = voteShare(TRAIN, x, y, k, m)
    const cls = (f > 0.5 ? 1 : 0) as 0 | 1
    const level = Math.max(1, Math.ceil(Math.abs(2 * f - 1) * 3 - 1e-9))
    return { cls, level }
  }
  for (let j = 0; j < n; j++) {
    const yc = lo + (j + 0.5) * step
    let start = 0
    let cur = key(lo + 0.5 * step, yc)
    for (let i = 1; i <= n; i++) {
      const v = i < n ? key(lo + (i + 0.5) * step, yc) : null
      if (!v || v.cls !== cur.cls || v.level !== cur.level) {
        runs.push({ x0: lo + start * step, x1: lo + i * step, y0: lo + j * step, y1: lo + (j + 1) * step, ...cur })
        if (v) {
          start = i
          cur = v
        }
      }
    }
  }
  return runs
}

